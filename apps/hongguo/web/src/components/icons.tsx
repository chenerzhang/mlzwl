/** 图标尺寸。集中定义，避免各处写不同的 `h-*` / `w-*`。 */
export type IconSize = 'sm' | 'md' | 'lg';

/**
 * 尺寸走 SVG 的 `width` / `height` 呈现属性，**不走 Tailwind 类**。
 *
 * 原因：`h-5 w-5` 与调用方补的 `h-8 w-8` 同时存在时，谁生效取决于 Tailwind
 * 生成 CSS 的规则顺序，而不是 `className` 字符串顺序，属于不确定行为。
 * 呈现属性的优先级低于任何 CSS 类，所以调用方真需要特殊尺寸时，传一个
 * `h-*` / `w-*` 就能确定性地覆盖默认值。
 */
const SIZE_PX: Record<IconSize, number> = {
  sm: 16,
  md: 20,
  lg: 24,
};

export interface IconProps {
  /** 视觉尺寸。默认 `md`（20px）。 */
  size?: IconSize;
  /** 额外的 class，例如颜色或 `flex-none`。 */
  className?: string;
}

/**
 * 图标外壳。
 *
 * `viewBox` 固定 256×256（Phosphor 原始坐标系），`fill="currentColor"` 让颜色
 * 跟随文字色——不要给图标写死颜色，否则深浅色主题要维护两套。
 *
 * `aria-hidden` 与 `focusable="false"` 一起给：前者让辅助技术跳过图标，后者
 * 防止 IE/旧 Edge 把 SVG 放进 Tab 序列。
 */
function Icon({ size = 'md', className = '', children }: IconProps & { children: React.ReactNode }): React.JSX.Element {
  const px = SIZE_PX[size];
  return (
    <svg
      viewBox="0 0 256 256"
      width={px}
      height={px}
      aria-hidden="true"
      focusable="false"
      fill="currentColor"
      className={`flex-none ${className}`.trim()}
    >
      {children}
    </svg>
  );
}

